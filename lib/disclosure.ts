export function plainFiling(title: string) {
  const fix = /^\[(기재정정|첨부정정|첨부추가|변경등록|연장결정|발행조건확정|정정명령부과|정정제출요구)\]/.test(title) ? "앞서 낸 공시를 고치거나 보탠 내용이에요. " : "";
  const body = title.replace(/^\[[^\]]+\]/, "");
  const hit = KINDS.find(([re]) => re.test(body));
  return fix + (hit ? hit[1] : "회사가 공식으로 알린 공시예요. 원문에서 내용을 확인해 주세요.");
}
